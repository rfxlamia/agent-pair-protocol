function pickCodeWord(): string {
  const word = CODE_WORDS[randomInt(CODE_WORDS.length)];
  if (!word) {
    throw new Error("CODE_WORDS must not be empty");
  }
  return word;
}

export function generatePairingCode(): string {
  const num = randomInt(10, 100);
  const a = pickCodeWord();
  const b = pickCodeWord();
  const c = pickCodeWord();
  return `${num}-${a}-${b}-${c}`;
}
